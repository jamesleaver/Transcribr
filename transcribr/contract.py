"""The parts of the JSON contract Python can state for itself.

Deliberately not imported by __init__: this is a build-time generator,
not something the running app needs, and importing it there makes
`python3 -m transcribr.contract` warn about executing a module that is
already imported.


web/src/api/types.ts used to declare all of it by hand, which meant a
renamed settings key was a silent `undefined` in the browser rather
than a build error. Everything in here is already described in Python -
the settings defaults, which keys are booleans, which are numbers, what
values the enumerated ones accept, what a palette contains - so the
TypeScript for those is generated from it instead of typed twice.

Regenerate with:

    python3 -m transcribr.contract web/src/api/contract.generated.ts

(Pass the path rather than redirecting: a shell redirect on Windows
turns every newline into a carriage return and newline, and the file is
checked in.)

test_contract.py fails if the checked-in file is not what this module
produces, so the two cannot drift apart unnoticed.

Only the parts Python genuinely owns are generated. The response shapes
that are assembled in route handlers - the review payload, /api/meta -
are still declared by hand in types.ts, and the test at the bottom of
test_contract.py at least holds the settings half of that honest.
"""

from .palettes import _PALETTES
from .runctl import RUN_PHASES
from .settings import (
    _SETTINGS_BOOL_KEYS, _SETTINGS_NUMBER_KEYS, _settings_choices,
    default_settings,
)

# Enumerated settings whose values are fixed by the app rather than by
# what happens to be installed. The rest (engine, model, language,
# diarize_model) vary per machine, so they are plain strings in
# TypeScript.
FIXED_CHOICE_SETTINGS = ("task", "output_format", "doc_template", "theme",
                         "word_timestamps")

# What each setting is for, in the generated interface. The prose lived
# in types.ts; it belongs beside the thing it describes.
SETTINGS_DOC = {
    "title": "Document title (heading). Never sent to the engine.",
    "offer_indistinct":
        "Offer [indistinct] in review for passages the engine was unsure "
        "of. Never applied without the reviewer.",
    "doc_template":
        "Word layout: plain, court (numbered lines, double spaced, running "
        "header) or erisp (record-of-interview heading, numbered lines).",
    "prompt": "Optional initial_prompt / vocabulary hint. Opt-in; can "
              "backfire.",
    "gap": "Start a new paragraph after a silence of this many seconds.",
    "colour_speakers":
        "Shade each speaker's paragraphs in .docx/.pdf with the review "
        "pane's colours. Plain text has nowhere to put a colour.",
    "show_prompt":
        "Show the context/vocabulary priming field on the Transcribe page.",
    "show_diarize":
        "Show the experimental speaker-detection card on the Transcribe "
        "page.",
    "prime_with_terms":
        "Feed confirmed names back to the engine as context. Off by "
        "default: priming can make the engine hear a name where none "
        "was said.",
    "voice_breaks":
        "Start a new paragraph where the voice changes pitch sharply "
        "after a finished sentence - usually a new speaker.",
    "auto_retranscribe":
        "Re-run the sections that look like engine error before the "
        "review pane opens.",
    "word_timestamps":
        "Word-level timing & confidence highlighting.",
}


def _ts_type(key, value, choices):
    if key in _SETTINGS_BOOL_KEYS:
        return "boolean"
    if key in _SETTINGS_NUMBER_KEYS:
        return "number"
    if key in FIXED_CHOICE_SETTINGS and choices.get(key):
        return " | ".join(f'"{v}"' for v in choices[key])
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, (int, float)):
        return "number"
    return "string"


def _doc_comment(key, indent="  "):
    text = SETTINGS_DOC.get(key)
    if not text:
        return []
    words, lines, current = text.split(), [], ""
    for w in words:
        if len(current) + len(w) + 1 > 68:
            lines.append(current)
            current = w
        else:
            current = f"{current} {w}".strip()
    if current:
        lines.append(current)
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    out = [f"{indent}/** {lines[0]}"]
    out += [f"{indent} *  {ln}" for ln in lines[1:]]
    out.append(f"{indent} */")
    return out


def typescript_contract():
    """The generated TypeScript, as a string."""
    defaults = default_settings()
    choices = _settings_choices()
    palette = _PALETTES["light"]

    out = [
        "// GENERATED by `python3 -m transcribr.contract` - do not edit.",
        "//",
        "// Python owns these shapes (settings defaults and their",
        "// validation, the palettes, the run phases), so they are",
        "// generated from it rather than declared twice. Change them in",
        "// Python and regenerate; test_contract.py fails if this file is",
        "// stale.",
        "",
        "/** Same keys and value conventions as settings.json. */",
        "export interface Settings {",
    ]
    for key, value in defaults.items():
        out += _doc_comment(key)
        out.append(f"  {key}: {_ts_type(key, value, choices)};")
    out += ["}", ""]

    theme = " | ".join(f'"{v}"' for v in choices["theme"])
    out += [f"export type ThemeSetting = {theme};", ""]

    out += ["/** Transcript-semantic colours served from Python's "
            "_PALETTES. */",
            "export interface Palette {"]
    for key, value in palette.items():
        if isinstance(value, dict):
            slots = " | ".join(f'"{k}"' for k in value)
            out.append(f"  {key}: Record<{slots}, string>;")
        else:
            out.append(f"  {key}: string;")
    out += ["}", ""]

    phases = "\n".join(f'  | "{p}"' for p in RUN_PHASES)
    out += ["export type RunPhase =", phases + ";", ""]

    out += ["/** The settings whose values this build fixes. */",
            "export const SETTING_CHOICES = {"]
    for key in FIXED_CHOICE_SETTINGS:
        values = ", ".join(f'"{v}"' for v in choices[key])
        out.append(f"  {key}: [{values}],")
    out += ["} as const;", ""]

    return "\n".join(out)


def write_contract(path):
    """Write the generated TypeScript to `path` with Unix newlines
    whatever the platform, so the checked-in file is identical
    everywhere."""
    import pathlib
    pathlib.Path(path).write_text(typescript_contract(),
                                  encoding="utf-8", newline="\n")


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1:
        write_contract(sys.argv[1])
    else:                       # stdout, for a quick look
        sys.stdout.write(typescript_contract())
